import { join } from 'node:path';
import { walkFrom, type WalkEdge, type WalkGraph, type WalkNode } from '../../src/kural/walk.ts';
import { EVAL, readJson, REPO, writeText } from './lib/paths.ts';

/** Every walk as a reader sees it, in one file, for reviewing without opening each page. tests/walks.test.ts holds the site to it. */
const data = readJson<{ nodes: (WalkNode & { snippet: string })[]; edges: WalkEdge[] }>(join(REPO, 'public', 'data', 'kural-graph.json'));
const g: WalkGraph = { nodeById: new Map(data.nodes.map((n) => [n.id, n])), edges: data.edges };
const label = (id: string): string => g.nodeById.get(id)!.label;
const text = (id: string): string => (g.nodeById.get(id) as unknown as { snippet: string }).snippet;

const lines = ['# Every walk, as a reader sees it', '', 'Generated by `node content/pipeline/flows-print.ts`. "Via" means a general answer to that feeling, pulled in automatically.'];
for (const node of data.nodes.filter((n) => n.type === 'LifeDilemma')) {
  const walk = walkFrom(g, node.id)!;
  lines.push('', `## ${walk.situation.label}`, '');
  for (const f of walk.feelings) lines.push(`- **Can feel like ${f.label}:** ${f.reason}`);
  for (const way of walk.ways) {
    const via = way.direct ? '' : ` (via ${way.answers.map(label).join(', ')})`;
    lines.push(`- **${way.label}${via}:** ${way.reason}`);
    for (const n of way.couplets) lines.push(`  - K${n.slice(2)}: ${text(n)}`);
  }
  if (walk.silent !== undefined) lines.push(`- **What the Kural doesn’t offer:** ${walk.silent}`);
  for (const n of walk.also) lines.push(`- Also K${n.slice(2)}: ${text(n)}`);
}
writeText(join(EVAL, 'walks.md'), `${lines.join('\n')}\n`);
console.log(`Wrote ${join(EVAL, 'walks.md')}`);
